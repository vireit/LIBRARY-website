-- ---------- справочники ----------

CREATE TABLE IF NOT EXISTS genres (
    id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS authors (
    id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  TEXT NOT NULL UNIQUE
);

-- ---------- каталог ----------

CREATE TABLE IF NOT EXISTS books (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        TEXT     NOT NULL CHECK (char_length(title) BETWEEN 1 AND 200),
    author_id    INTEGER  NOT NULL REFERENCES authors (id) ON DELETE RESTRICT,
    genre_id     INTEGER  NOT NULL REFERENCES genres  (id) ON DELETE RESTRICT,
    year         SMALLINT NOT NULL CHECK (year BETWEEN 1000 AND 2100),
    pages        SMALLINT NOT NULL CHECK (pages > 0),
    hue          SMALLINT NOT NULL DEFAULT 30 CHECK (hue BETWEEN 0 AND 360),   -- цвет сгенерированной обложки
    quote        TEXT     NOT NULL,                                            -- цитата или короткая строка о книге
    description  TEXT     NOT NULL,
    moods        TEXT[]   NOT NULL DEFAULT '{}'
                 CHECK (moods <@ ARRAY['calm', 'think', 'thrill', 'dream']),   -- для подбора книги
    is_new       BOOLEAN  NOT NULL DEFAULT FALSE,                              -- новинка
    is_hit       BOOLEAN  NOT NULL DEFAULT FALSE,                              -- хит
    is_soon      BOOLEAN  NOT NULL DEFAULT FALSE,                              -- скоро в наличии
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS books_author_idx ON books (author_id);
CREATE INDEX IF NOT EXISTS books_genre_idx  ON books (genre_id);

-- ---------- читатели ----------

CREATE TABLE IF NOT EXISTS users (
    id             INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    username       TEXT NOT NULL UNIQUE CHECK (username ~ '^[a-z0-9_.-]{3,24}$'),
    name           TEXT NOT NULL CHECK (char_length(name) BETWEEN 1 AND 40),
    email          TEXT CHECK (email IS NULL OR email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    password_hash  TEXT NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------- выдача книг ----------

CREATE TABLE IF NOT EXISTS loans (
    id           BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id      INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    book_id      INTEGER NOT NULL REFERENCES books (id) ON DELETE RESTRICT,
    taken_on     DATE    NOT NULL DEFAULT CURRENT_DATE,
    due_on       DATE    NOT NULL,
    returned_on  DATE,                                  -- NULL = книга ещё на руках
    extended     BOOLEAN NOT NULL DEFAULT FALSE,        -- срок продлевали (можно один раз)
    CHECK (due_on >= taken_on),
    CHECK (returned_on IS NULL OR returned_on >= taken_on)
);
-- Одну и ту же книгу нельзя держать на руках дважды (защита на уровне базы)
CREATE UNIQUE INDEX IF NOT EXISTS loans_one_active_per_book
    ON loans (user_id, book_id) WHERE returned_on IS NULL;
CREATE INDEX IF NOT EXISTS loans_user_idx ON loans (user_id, returned_on);
CREATE INDEX IF NOT EXISTS loans_book_idx ON loans (book_id);

-- ---------- избранное (книги, мероприятия, новости) ----------

CREATE TABLE IF NOT EXISTS favorites (
    user_id  INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    kind     TEXT    NOT NULL CHECK (kind IN ('book', 'event', 'news')),
    item_id  INTEGER NOT NULL,
    PRIMARY KEY (user_id, kind, item_id)
);

-- ---------- события и новости ----------

CREATE TABLE IF NOT EXISTS events (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      TEXT NOT NULL,
    tag        TEXT NOT NULL,
    place      TEXT NOT NULL,
    starts_at  TIMESTAMP NOT NULL,                      -- местное время библиотеки
    body       TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS events_starts_idx ON events (starts_at);

CREATE TABLE IF NOT EXISTS news (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title         TEXT NOT NULL,
    tag           TEXT NOT NULL,
    published_on  DATE NOT NULL DEFAULT CURRENT_DATE,
    body          TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS news_published_idx ON news (published_on DESC);

-- ---------- сообщения из формы «Контакты» ----------

CREATE TABLE IF NOT EXISTS messages (
    id          INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL,
    email       TEXT,
    body        TEXT NOT NULL,
    is_read     BOOLEAN NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------- удобное представление для сайта ----------
-- Склеивает книгу с автором и жанром и называет колонки так, как их ждёт интерфейс.

CREATE OR REPLACE VIEW v_books AS
SELECT b.id,
       b.title,
       a.name        AS author,
       b.year,
       g.name        AS genre,
       b.pages,
       b.hue,
       b.quote       AS line,
       b.description AS "desc",
       b.moods,
       b.is_new      AS "new",
       b.is_hit      AS "hit",
       b.is_soon     AS "soon"
FROM books b
JOIN authors a ON a.id = b.author_id
JOIN genres  g ON g.id = b.genre_id;

-- ---------- подписи для pgAdmin ----------

COMMENT ON TABLE books     IS 'Каталог книг';
COMMENT ON TABLE users     IS 'Читатели (пароли хранятся только в виде хеша)';
COMMENT ON TABLE loans     IS 'Выдачи книг: returned_on IS NULL — книга на руках';
COMMENT ON TABLE favorites IS 'Избранное: kind = book / event / news';
COMMENT ON TABLE events    IS 'Мероприятия библиотеки';
COMMENT ON TABLE news      IS 'Новости библиотеки';
COMMENT ON TABLE messages  IS 'Сообщения из формы обратной связи';
